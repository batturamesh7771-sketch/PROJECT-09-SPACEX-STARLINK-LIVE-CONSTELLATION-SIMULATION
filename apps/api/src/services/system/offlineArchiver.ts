export async function generateOfflineSnapshotManifest(): Promise<OfflineSnapshotManifest> {
  const [exoplanets, gravitationalWaves, dsnLinks, eonetEvents, neos] =
    await Promise.all([
      fetchExoplanets().catch(() => []),
      fetchGravitationalWaveEvents().catch(() => []),
      fetchDsnTelemetryLinks().catch(() => []),
      fetchEonetNaturalEvents(25).catch(() => []),
      fetchNeoCloseApproaches(15).catch(() => []),
    ]);

  return {
    version: '1.0.0-phase6',
    generatedAt: new Date().toISOString(),
    platform: 'Project COSMOS Offline Archive',
    counts: {
      satellites: EMBEDDED_OFFLINE_TLES.length,
      constellations: 12,
      exoplanets: exoplanets.length,
      gravitationalWaves: gravitationalWaves.length,
      dsnLinks: dsnLinks.length,
      eonetEvents: eonetEvents.length,
      neos: neos.length,
    },
    tles: EMBEDDED_OFFLINE_TLES,
    spaceWeatherSummary: {
      kpIndex: 3.3,
      stormLevel: 'G0 (Quiet)',
      solarWindSpeedKms: 438,
    },
    exoplanets,
    gravitationalWaves,
    dsnLinks,
  };
}
